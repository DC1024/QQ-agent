// 51 宿主授权：清单不得自我授权、setup 权限、持久化/撤销/更新和待确认竞态。
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { mktmp, section } from './helpers.mjs';
import { createPluginLoader } from '../src/kernel/plugin-loader.js';
import { createToolRegistry } from '../src/kernel/tools.js';
import { createCapabilityRegistry } from '../src/kernel/capability.js';
import { createPermissions } from '../src/kernel/permissions.js';
import { createScheduler } from '../src/kernel/scheduler.js';
import { createStorage } from '../src/kernel/storage.js';
import { createConfig, buildDefaultConfig } from '../src/kernel/config.js';
import { Bus } from '../src/kernel/bus.js';
const log = { info() {}, warn() {}, error() {}, child() { return this; } };
const root = mktmp('qqa-host-grants-');
const dataDir = mktmp('qqa-host-grants-data-');
for (const dir of ['bundled', 'plugins', 'skills']) fs.mkdirSync(path.join(root, dir));
fs.writeFileSync(path.join(root, 'package.json'), '{"type":"module"}');
const compatUrl = pathToFileURL(path.resolve(import.meta.dirname, '../bundled/compat-04/index.js')).href;
fs.mkdirSync(path.join(root, 'bundled', 'compat-04'));
fs.writeFileSync(path.join(root, 'bundled', 'compat-04', 'skill.json'), '{"id":"compat-04","kind":"plugin"}');
fs.writeFileSync(path.join(root, 'bundled', 'compat-04', 'index.js'), `export {default} from ${JSON.stringify(compatUrl)};`);
const pluginDir = path.join(root, 'skills', 'legacy');
fs.mkdirSync(pluginDir);
fs.writeFileSync(path.join(pluginDir, 'skill.json'), JSON.stringify({ id: 'legacy', compat: '04', legacyTrusted: true, permissions: ['web_fetch'] }));
const source = `export default {async setup(api){const response=await api.fetch('https://fixture.test');api.registerTool({id:'ping',name:'Ping',execute:()=>response.status});}};`;
fs.writeFileSync(path.join(pluginDir, 'index.js'), source);
let fetchCalls = 0;
function environment() {
  const bus = new Bus(log), permissions = createPermissions({ dataDir, log, bus, headless: true });
  const caps = createCapabilityRegistry({ log }), registry = createToolRegistry({ log, bus, permissions, capabilities: caps });
  const scheduler = createScheduler({ log }), storage = createStorage({ dataDir, log });
  const config = createConfig({ dataDir, defaults: buildDefaultConfig(), log }); config.load();
  caps.register('compat04.http', 'kernel', { fetchFor: async () => { fetchCalls++; return new Response('ok', { status: 200 }); } });
  const loader = createPluginLoader({ log, bus, appRoot: root, registry, capabilityRegistry: caps, permissions, scheduler, storage, config,
  });
  return { loader, permissions, registry, scheduler };
}
const e = environment();
section('清单 legacyTrusted=true 不能自我授权；setup 请求被拒');
await e.loader.loadAll();
assert.equal(e.loader.isActive('legacy'), false);
assert.equal(fetchCalls, 0);
assert.equal(e.permissions.status('legacy', 'net.outbound').override, null);
const fingerprint = e.loader.hostEntry('legacy').fingerprint;
assert.match(fingerprint, /^[a-f0-9]{64}$/);
section('管理员显式授权在 setup 前生效，并保存宿主文件');
assert.equal(e.permissions.setOverride('legacy', 'net.outbound', 'allow', { fingerprint }), true);
await e.loader.loadDir('skills', pluginDir);
assert.equal(e.loader.isActive('legacy'), true);
assert.equal(fetchCalls, 1);
assert.equal(e.registry.get('legacy__ping').ownerId, 'legacy');
assert.equal(fs.existsSync(path.join(dataDir, 'plugin-authorizations.json')), true);
section('重启同一版本继承宿主授权');
e.loader.stopAll(); e.scheduler.stop();
const e2 = environment(); await e2.loader.loadAll();
assert.equal(e2.loader.isActive('legacy'), true);
assert.equal(fetchCalls, 2);
section('撤销立即生效，不会被重载或清单重新放行');
assert.equal(e2.permissions.setOverride('legacy', 'net.outbound', 'deny', { fingerprint }), true);
await e2.loader.loadDir('skills', pluginDir);
assert.equal(fetchCalls, 2);
assert.equal(e2.permissions.check('legacy', 'net.outbound', { fingerprint }).decision, 'deny');
assert.equal(e2.permissions.status('legacy', 'net.outbound').override, 'deny');
section('代码更新（不改 version）废弃旧 allow，不按 mtime 猜');
e2.permissions.setOverride('legacy', 'net.outbound', 'allow', { fingerprint });
fs.writeFileSync(path.join(pluginDir, 'index.js'), `${source}\n// code changed`);
assert.equal(e2.permissions.check('legacy', 'net.outbound', { fingerprint }).decision, 'deny');
await e2.loader.loadDir('skills', pluginDir);
assert.equal(fetchCalls, 2);
assert.notEqual(e2.loader.hostEntry('legacy').fingerprint, undefined);
assert.equal(e2.permissions.setOverride('legacy', 'net.outbound', 'allow', { fingerprint }), false);
e2.loader.stopAll(); e2.scheduler.stop();
section('异步确认绑定指纹；旧请求、撤销与关机全部 fail-closed');
const f1 = '1'.repeat(64), f2 = '2'.repeat(64);
const pm = createPermissions({ dataDir: mktmp('qqa-persist-ask-'), log });
pm.bindPlugin('p', { fingerprint: f1, scopes: ['net.outbound'] });
const waiting = pm.checkAsync('p', 'net.outbound', { fingerprint: f1 });
const request = pm.pending()[0];
pm.bindPlugin('p', { fingerprint: f2, scopes: ['net.outbound'] });
assert.equal((await waiting).decision, 'deny');
assert.equal(pm.resolveAsk(request.id, 'always').ok, false);
const waiting2 = pm.checkAsync('p', 'net.outbound', { fingerprint: f2 });
pm.setOverride('p', 'net.outbound', 'deny', { fingerprint: f2 });
assert.equal((await waiting2).decision, 'deny');
assert.equal(pm.check('p', 'net.raw').decision, 'deny');
pm.setOverride('p', 'net.outbound', 'ask', { fingerprint: f2 });
const waiting3 = pm.checkAsync('p', 'net.outbound', { fingerprint: f2 });
pm.close(); assert.equal((await waiting3).decision, 'deny');
section('once凭据不重新请求，异步hook等待期间撤销使其失效');
const p = createPermissions({log:{}}), tools = createToolRegistry({permissions:p,log:{}});
let ran=0, release, entered;
const atHook=new Promise(resolve=>{entered=resolve;});
tools.register({id:'once_tool',name:'Once',ownerId:'once-plugin',scopes:['net.outbound'],execute:()=>{ran++;return 'ran';}});
const running=tools.invoke('once_tool',{}, {beforeToolHooks:[async()=>{entered();await new Promise(resolve=>{release=resolve;});}]});
const onceRequest=p.pending()[0];assert.ok(onceRequest);p.resolveAsk(onceRequest.id,'once');
await atHook;p.setOverride('once-plugin','net.outbound','ask');release();
assert.equal((await running).ok,false);assert.equal(ran,0);assert.equal(p.pending().length,0);
p.close();
